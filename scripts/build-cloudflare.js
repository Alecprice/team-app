import {build} from 'esbuild';
import fs from 'node:fs/promises';
import path from 'node:path';
import {fileURLToPath} from 'node:url';
const root=path.resolve(path.dirname(fileURLToPath(import.meta.url)),'..');
const dist=path.join(root,'dist');
const pkg=JSON.parse(await fs.readFile(path.join(root,'package.json'),'utf8'));
const DEFAULT_AUTH='https://ep-noisy-violet-awtos8ns.neonauth.c-12.us-east-1.aws.neon.tech/neondb/auth';
const DEFAULT_DATA='https://ep-noisy-violet-awtos8ns.apirest.c-12.us-east-1.aws.neon.tech/neondb/rest/v1';
const authUrl=process.env.TEAM_APP_NEON_AUTH_URL||DEFAULT_AUTH;
const dataUrl=process.env.TEAM_APP_NEON_DATA_API_URL||DEFAULT_DATA;
const buildEnv=process.env.TEAM_APP_ENV||process.env.CF_PAGES_BRANCH||'local';
const commitSha=process.env.CF_PAGES_COMMIT_SHA||process.env.GITHUB_SHA||'local';
const endpointPlugin={name:'team-app-cloud-endpoints',setup(ctx){ctx.onLoad({filter:/client\/(?:cloud-entry|cloud-admin-hardening)\.js$/},async args=>{let contents=await fs.readFile(args.path,'utf8');contents=contents.replaceAll(DEFAULT_AUTH,authUrl).replaceAll(DEFAULT_DATA,dataUrl);return {contents,loader:'js'};});}};
await fs.rm(dist,{recursive:true,force:true});await fs.mkdir(dist,{recursive:true});
await build({entryPoints:[path.join(root,'client/cloud-entry-hardened.js')],bundle:true,minify:true,sourcemap:false,format:'iife',platform:'browser',target:['es2022'],outfile:path.join(dist,'cloud-client.js'),plugins:[endpointPlugin],define:{'process.env.NODE_ENV':'"production"'}});
const files=['index.html','styles.css','sports.js','competition-profiles.js','app.js','sw.js','manifest.webmanifest','_headers'];
for(const f of files)await fs.copyFile(path.join(root,f),path.join(dist,f));
for(const dir of ['core','icons'])await fs.cp(path.join(root,dir),path.join(dist,dir),{recursive:true});
await fs.writeFile(path.join(dist,'build-info.json'),JSON.stringify({app:'team-app',version:pkg.version,environment:buildEnv,commit:commitSha,builtAt:new Date().toISOString()},null,2)+'\n');
console.log('Built Team APP static Cloudflare Pages output:',dist);
console.log(`Environment: ${buildEnv} · commit: ${commitSha}`);
